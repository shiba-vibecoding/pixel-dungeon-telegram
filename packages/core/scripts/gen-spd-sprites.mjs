// Generates packages/core/src/spd-sprites.ts from Shattered Pixel Dungeon's ItemSpriteSheet.java.
// Usage: node packages/core/scripts/gen-spd-sprites.mjs [path/to/ItemSpriteSheet.java]
// Default source: ../spd-src (next to pd-ts). The output is committed; the Java file is only a reference.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(process.argv[2] ?? resolve(here, '../../../../spd-src/core/src/main/java/com/shatteredpixel/shatteredpixeldungeon/sprites/ItemSpriteSheet.java'));
const out = resolve(here, '../src/spd-sprites.ts');
const java = readFileSync(src, 'utf8');

/** Splits the file into the outer sheet and the nested Icons class. */
const iconsAt = java.indexOf('public static class Icons');
if (iconsAt < 0) throw new Error('no Icons class in ' + src);
const sections = [
  { name: 'S', title: 'items.png (256×512, 16 per row, 16 px cells)', body: java.slice(0, iconsAt) },
  { name: 'I', title: 'item_icons.png (128×64, 16 per row, 8 px cells)', body: java.slice(iconsAt) },
];

function parse(body) {
  const width = 16; // both sheets: WIDTH = 16 cells per row
  const vals = new Map();
  const pub = [];
  const decl = /(public|private)\s+static\s+final\s+int\s+([A-Z0-9_]+)\s*=\s*([^;]+);/g;
  for (const m of body.matchAll(decl)) {
    const [, vis, name, exprRaw] = m;
    if (name === 'SIZE' || name === 'WIDTH' || name.startsWith('TX_')) continue;
    const expr = exprRaw.trim();
    let v;
    let xy;
    if ((xy = /^xy\(\s*(\d+)\s*,\s*(\d+)\s*\)$/.exec(expr))) {
      v = (Number(xy[1]) - 1) + width * (Number(xy[2]) - 1);
    } else {
      const off = /^([A-Z0-9_]+)\s*(?:\+\s*(\d+))?$/.exec(expr);
      if (!off || !vals.has(off[1])) throw new Error(`cannot evaluate ${name} = ${expr}`);
      v = vals.get(off[1]) + Number(off[2] ?? 0);
    }
    vals.set(name, v);
    if (vis === 'public') pub.push([name, v]);
  }
  return pub;
}

let ts = `// GENERATED by packages/core/scripts/gen-spd-sprites.mjs from Shattered Pixel Dungeon v4.0.2's
// sprites/ItemSpriteSheet.java (Evan Debenham, GPL-3.0). Do not edit by hand; rerun the script.\n`;
for (const s of sections) {
  const consts = parse(s.body);
  const seen = new Set();
  for (const [n] of consts) { if (seen.has(n)) throw new Error('duplicate ' + n); seen.add(n); }
  ts += `\n/** Cells of ${s.title}. */\nexport const ${s.name} = {\n`;
  for (const [n, v] of consts) ts += `  ${n}: ${v},\n`;
  ts += `} as const;\n`;
  console.log(`${s.name}: ${consts.length} constants`);
}
ts += `\nexport type SpdSprite = (typeof S)[keyof typeof S];\nexport type SpdIcon = (typeof I)[keyof typeof I];\n`;
writeFileSync(out, ts);
console.log('wrote', out);
