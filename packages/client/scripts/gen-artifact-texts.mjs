// Generates packages/client/src/i18n-artifacts.ts from Shattered Pixel Dungeon's message files: the artifacts'
// texts (items.artifacts.*, keyed without that prefix), the rings' (items.rings.*) and the few other lines their
// rules say, in English and Russian.
// Usage: node packages/client/scripts/gen-artifact-texts.mjs [path/to/spd-src]
// Default source: ../spd-src (next to pd-ts). The output is committed; the message files are only a reference.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const spd = resolve(process.argv[2] ?? resolve(here, '../../../../spd-src'));
const messages = resolve(spd, 'core/src/main/assets/messages');
const out = resolve(here, '../src/i18n-artifacts.ts');

/** Artifacts this game has none of (the cleric's tome, the vault's key). */
const SKIP = ['holytome', 'skeletonkey'];
/** Other lines the artifacts' rules say, by their full keys. */
const EXTRA = [
  'actors.buffs.hunger.cursedhorn', 'actors.mobs.npcs.shopkeeper.thief', 'items.scrolls.scrollofteleportation.no_tele',
  'windows.wndtradeitem.steal', 'windows.wndtradeitem.steal_warn', 'windows.wndtradeitem.steal_warn_yes', 'windows.wndtradeitem.steal_warn_no',
  'items.kindofmisc.unequip_title', 'items.kindofmisc.unequip_message',
  'actors.buffs.artifactrecharge.name',
];

function read(file) {
  const map = new Map();
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const at = line.indexOf('=');
    if (at <= 0 || line.startsWith('#')) continue;
    map.set(line.slice(0, at).trim(), line.slice(at + 1));
  }
  return map;
}

/** Shattered's markup: \n for a new line, _highlight_ (plain here), '' for a quote in MessageFormat. */
const clean = (text) => text.replace(/\\n/g, '\n').replace(/_([^_\n]+)_/g, '$1').replace(/\\'/g, "'");

function texts(lang) {
  const suffix = lang === 'en' ? '' : `_${lang}`;
  const all = new Map([
    ...read(resolve(messages, `items/items${suffix}.properties`)),
    ...read(resolve(messages, `actors/actors${suffix}.properties`)),
    ...read(resolve(messages, `windows/windows${suffix}.properties`)),
  ]);
  const result = {};
  for (const [key, value] of all) {
    if (!key.startsWith('items.artifacts.')) continue;
    const short = key.slice('items.artifacts.'.length);
    if (SKIP.some((skip) => short.startsWith(skip))) continue;
    result[short] = clean(value);
  }
  for (const key of EXTRA) if (all.has(key)) result[key] = clean(all.get(key));
  // Shattered's rings (items.rings.*), whole keys: names, descriptions and their stats lines.
  for (const [key, value] of all) if (key.startsWith('items.rings.')) result[key] = clean(value);
  return result;
}

const en = texts('en');
const ru = texts('ru');
// Every key in both; a line missing in Russian stays English.
for (const key of Object.keys(en)) ru[key] ??= en[key];
const body = (obj) => Object.keys(en).sort().map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(obj[key])},`).join('\n');

// One file for each language: the page loads only the one it shows (see i18n.ts).
const header = `// Generated by packages/client/scripts/gen-artifact-texts.mjs from Shattered Pixel Dungeon's message files
// (core/src/main/assets/messages, GPL-3.0): the artifacts' names, descriptions and lines, keyed as there without
// the items.artifacts. prefix, and the few other lines the artifacts' rules say. Do not edit by hand.

`;
writeFileSync(out, `${header}export const ART_EN: Record<string, string> = {
${body(en)}
};
`);
writeFileSync(out.replace(/\.ts$/, '.ru.ts'), `${header}export const ART_RU: Record<string, string> = {
${body(ru)}
};
`);
console.log(`${Object.keys(en).length} texts written to ${out}`);
