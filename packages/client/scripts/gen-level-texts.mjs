// Generates packages/client/src/i18n-levels.ts from Shattered Pixel Dungeon's message files: what the levels
// stream brings in — the levels' terrain names and descriptions, feelings, traps, rooms, custom tiles (levels.*),
// the quests' characters, monsters, items and windows, the shops, keys and bags — in English and Russian, keyed
// by their full keys.
// Usage: node packages/client/scripts/gen-level-texts.mjs [path/to/spd-src]
// Default source: ../spd-src (next to pd-ts). The output is committed; the message files are only a reference.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const spd = resolve(process.argv[2] ?? resolve(here, '../../../../spd-src'));
const messages = resolve(spd, 'core/src/main/assets/messages');
const out = resolve(here, '../src/i18n-levels.ts');

/** Every key starting with one of these is taken. */
const PREFIXES = [
  'levels.',
  'tiles.',
  'actors.mobs.npcs.ghost', 'actors.mobs.npcs.wandmaker', 'actors.mobs.npcs.blacksmith', 'actors.mobs.npcs.imp',
  'actors.mobs.npcs.shopkeeper', 'actors.mobs.npcs.ratking', 'actors.mobs.npcs.vault',
  'actors.mobs.fetidrat', 'actors.mobs.gnolltrickster', 'actors.mobs.greatcrab', 'actors.mobs.rotheart', 'actors.mobs.rotlasher',
  'actors.mobs.elemental$newbornfireelemental', 'actors.mobs.crystalguardian', 'actors.mobs.crystalspire', 'actors.mobs.crystalwisp',
  'actors.mobs.gnollgeomancer', 'actors.mobs.gnollguard', 'actors.mobs.gnollsapper', 'actors.mobs.fungalcore', 'actors.mobs.fungalsentry',
  'actors.mobs.fungalspinner', 'actors.mobs.wraith', 'actors.mobs.statue', 'actors.mobs.armoredstatue', 'actors.mobs.piranha',
  'actors.mobs.demonspawner', 'actors.mobs.delayedrockfall',
  'actors.blobs.', 'actors.buffs.trap', 'actors.buffs.lockedfloor',
  'items.quest.', 'items.keys.', 'items.bags.', 'items.artifacts.skeletonkey', 'items.heap', 'items.journal.',
  'windows.wndblacksmith', 'windows.wndsadghost', 'windows.wndwandmaker', 'windows.wndimp', 'windows.wndtradeitem', 'windows.wndquest',
  'windows.wndinfotrap', 'windows.wndjournal', 'windows.wndkeyring', 'journal.notes', 'journal.document',
  'scenes.interlevelscene', 'scenes.gamescene.', 'plants.',
];

function read(file) {
  const map = new Map();
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const at = line.indexOf('=');
    if (at <= 0 || line.startsWith('#')) continue;
    map.set(line.slice(0, at).trim(), line.slice(at + 1));
  }
  return map;
}

/** Shattered's markup: \n for a new line, _highlight_ kept (the client styles it), '' for a quote in MessageFormat. */
const clean = (text) => text.replace(/\\n/g, '\n').replace(/\\'/g, "'").replace(/''/g, "'");

const FILES = ['levels/levels', 'actors/actors', 'items/items', 'windows/windows', 'journal/journal', 'scenes/scenes', 'plants/plants', 'misc/misc', 'ui/ui'];

function texts(lang) {
  const suffix = lang === 'en' ? '' : `_${lang}`;
  const all = new Map();
  for (const file of FILES) {
    try {
      for (const [k, v] of read(resolve(messages, `${file}${suffix}.properties`))) all.set(k, v);
    } catch {
      // A file this language lacks.
    }
  }
  const result = {};
  for (const [key, value] of all) if (PREFIXES.some((p) => key.startsWith(p))) result[key] = clean(value);
  return result;
}

const en = texts('en');
const ru = texts('ru');
// Every key in both; a line missing in Russian stays English.
for (const key of Object.keys(en)) ru[key] ??= en[key];
const body = (obj) => Object.keys(en).sort().map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(obj[key])},`).join('\n');

writeFileSync(out, `// Generated by packages/client/scripts/gen-level-texts.mjs from Shattered Pixel Dungeon's message files
// (core/src/main/assets/messages, GPL-3.0): the levels' terrains, feelings, traps and rooms, the quests' characters,
// monsters, items and windows, shops, keys and bags, keyed by their full keys. Do not edit by hand.

export const LEVELS_EN: Record<string, string> = {
${body(en)}
};

export const LEVELS_RU: Record<string, string> = {
${body(ru)}
};
`);
console.log(`${Object.keys(en).length} texts written to ${out}`);
