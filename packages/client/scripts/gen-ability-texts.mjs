// Generates packages/client/src/i18n-abilities.ts from Shattered Pixel Dungeon's message files: the armour abilities'
// texts (actors.hero.abilities.*), class armour and the Dwarf King's crown (items.armor.classarmor, *armor, kingscrown),
// the ability pick (windows.wndchooseability), and the tier 4 talents' titles and descriptions, in English and Russian.
// Usage: node packages/client/scripts/gen-ability-texts.mjs [path/to/spd-src]
// Default source: ../spd-src (next to pd-ts). The output is committed; the message files are only a reference.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const spd = resolve(process.argv[2] ?? resolve(here, '../../../../spd-src'));
const messages = resolve(spd, 'core/src/main/assets/messages');
const out = resolve(here, '../src/i18n-abilities.ts');

/** The abilities' classes this game has (the duelist's, the cleric's and the rat king's are the classes stream's). */
const CLASSES = ['armorability', 'warrior', 'mage', 'rogue', 'huntress'];
const TALENTS = [
  'body_slam', 'impact_wave', 'double_jump', 'expanding_wave', 'striking_wave', 'shock_force', 'sustained_retribution', 'shrug_it_off',
  'even_the_odds', 'blast_radius', 'elemental_power', 'reactive_barrier', 'wild_power', 'fire_everything', 'conserved_magic', 'telefrag',
  'remote_beacon', 'longrange_warp', 'hasty_retreat', 'body_replacement', 'shadow_step', 'fear_the_reaper', 'deathly_durability',
  'double_mark', 'shadow_blade', 'cloned_armor', 'perfect_copy', 'fan_of_blades', 'projecting_blades', 'spirit_blades', 'growing_power',
  'natures_wrath', 'wild_momentum', 'eagle_eye', 'go_for_the_eyes', 'swift_spirit', 'heroic_energy',
];
const EXTRA = [
  'windows.wndheroinfo.talents', 'items.armor.classarmor.', 'items.kingscrown.', 'windows.wndchooseability.',
];

function read(file) {
  const map = new Map();
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const at = line.indexOf('=');
    if (at <= 0 || line.startsWith('#')) continue;
    map.set(line.slice(0, at).trim(), line.slice(at + 1));
  }
  return map;
}

/** Shattered's markup: \n for a new line, _highlight_ (plain here), '' for a quote in MessageFormat. */
const clean = (text) => text.replace(/\\n/g, '\n').replace(/_([^_\n]+)_/g, '$1').replace(/\\'/g, "'");

const wanted = (key) =>
  CLASSES.some((cls) => key.startsWith(`actors.hero.abilities.${cls}.`)) ||
  TALENTS.some((name) => key.startsWith(`actors.hero.talent.${name}.`)) ||
  /^items\.armor\.(warrior|mage|rogue|huntress)armor\./.test(key) ||
  /^items\.wands\.\w+\.eleblast_desc$/.test(key) ||
  EXTRA.some((prefix) => key === prefix || (prefix.endsWith('.') && key.startsWith(prefix)));

function texts(lang) {
  const suffix = lang === 'en' ? '' : `_${lang}`;
  const all = new Map([
    ...read(resolve(messages, `items/items${suffix}.properties`)),
    ...read(resolve(messages, `actors/actors${suffix}.properties`)),
    ...read(resolve(messages, `windows/windows${suffix}.properties`)),
  ]);
  const result = {};
  for (const [key, value] of all) if (wanted(key)) result[key] = clean(value);
  return result;
}

const en = texts('en');
const ru = texts('ru');
// Every key in both; a line missing in Russian stays English.
for (const key of Object.keys(en)) ru[key] ??= en[key];
const body = (obj) => Object.keys(en).sort().map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(obj[key])},`).join('\n');

writeFileSync(out, `// Generated by packages/client/scripts/gen-ability-texts.mjs from Shattered Pixel Dungeon's message files
// (core/src/main/assets/messages, GPL-3.0): the armour abilities, class armour, the Dwarf King's crown and the tier 4
// talents, keyed as there. Do not edit by hand.

export const ABIL_EN: Record<string, string> = {
${body(en)}
};

export const ABIL_RU: Record<string, string> = {
${body(ru)}
};
`);
console.log(`${Object.keys(en).length} texts written to ${out}`);
