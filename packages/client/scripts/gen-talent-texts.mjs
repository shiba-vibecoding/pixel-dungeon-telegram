// Generates packages/client/src/i18n-talents.ts from Shattered Pixel Dungeon's message files: the talents' titles
// and descriptions, the subclasses', the buffs of the talents and subclasses, the windows' lines, in English and Russian.
// Usage: node packages/client/scripts/gen-talent-texts.mjs [path/to/spd-src]
// Default source: ../spd-src (next to pd-ts). The output is committed; the message files are only a reference.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const spd = resolve(process.argv[2] ?? resolve(here, '../../../../spd-src'));
const messages = resolve(spd, 'core/src/main/assets/messages');
const out = resolve(here, '../src/i18n-talents.ts');

/** The talents of the four classes, tiers 1 to 3 and the subclasses' third. */
const TALENTS = `hearty_meal veterans_intuition provoked_anger iron_will iron_stomach liquid_willpower runic_transference lethal_momentum
improvised_projectiles hold_fast strongman endless_rage deathless_fury enraged_catalyst cleave lethal_defense enhanced_combo
empowering_meal scholars_intuition lingering_magic backup_barrier energizing_meal inscribed_power wand_preservation arcane_vision
shield_battery desperate_power ally_warp empowered_strike mystical_charge excess_charge soul_eater soul_siphon necromancers_minions
cached_rations thiefs_intuition sucker_punch protective_shadows mystical_meal inscribed_stealth wide_search silent_steps rogues_foresight
enhanced_rings light_cloak enhanced_lethality assassins_reach bounty_hunter evasive_armor projectile_momentum speedy_stealth
natures_bounty survivalists_intuition followup_strike natures_aid invigorating_meal liquid_nature rejuvenating_steps heightened_senses
durable_projectiles point_blank seer_shot farsight shared_enchantment shared_upgrades durable_tips barkskin shielding_dew`.split(/\s+/);
const SUBCLASSES = ['berserker', 'gladiator', 'battlemage', 'warlock', 'assassin', 'freerunner', 'sniper', 'warden'];
/** Whole key prefixes to take. */
const PREFIXES = [
  'actors.buffs.berserk.', 'actors.buffs.combo', 'actors.buffs.holdfast.', 'actors.buffs.momentum.', 'actors.buffs.preparation.',
  'actors.buffs.snipersmark.', 'actors.buffs.wandempower.', 'actors.buffs.scrollempower.', 'actors.buffs.barkskin.',
  'actors.hero.talent$', 'actors.hero.hero.new_talent', 'windows.wndchoosesubclass.', 'windows.wndinfotalent.', 'windows.wndhero.',
  'windows.wndhero$', 'windows.wndheroinfo.', 'ui.talentspane.', 'items.tengusmask.', 'items.food.berry.', 'items.food.supplyration.',
  'items.scrolls.exotic.scrollofmetamorphosis.', 'items.weapon.melee.magesstaff.preserved', 'items.weapon.melee.magesstaff.imbue_talent',
  'scenes.gamescene.secret_hint', 'actors.mobs.monk.parried',
];

function read(file) {
  const map = new Map();
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const at = line.indexOf('=');
    if (at <= 0 || line.startsWith('#')) continue;
    map.set(line.slice(0, at).trim(), line.slice(at + 1));
  }
  return map;
}

/** Messages: \n for a new line, '' for a quote in MessageFormat; _emphasis_ is kept (the windows show it). */
const clean = (text) => text.replace(/\\n/g, '\n').replace(/\\'/g, "'").replace(/''/g, "'");

function texts(lang) {
  const suffix = lang === 'en' ? '' : `_${lang}`;
  const all = new Map();
  for (const [dir, name] of [['actors', 'actors'], ['windows', 'windows'], ['ui', 'ui'], ['items', 'items'], ['scenes', 'scenes']]) {
    for (const [key, value] of read(resolve(messages, `${dir}/${name}${suffix}.properties`))) all.set(key, value);
  }
  const result = {};
  for (const [key, value] of all) {
    const talent = TALENTS.some((id) => key.startsWith(`actors.hero.talent.${id}.`));
    const sub = SUBCLASSES.some((id) => key.startsWith(`actors.hero.herosubclass.${id}`));
    const plant = key.startsWith('plants.') && key.endsWith('.warden_desc');
    if (talent || sub || plant || PREFIXES.some((prefix) => key.startsWith(prefix))) result[key] = clean(value);
  }
  return result;
}

const en = texts('en');
const ru = texts('ru');
for (const key of Object.keys(en)) ru[key] ??= en[key];
const body = (obj) => Object.keys(en).sort().map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(obj[key])},`).join('\n');

// One file for each language: the page loads only the one it shows (see i18n.ts).
const header = `// Generated by packages/client/scripts/gen-talent-texts.mjs from Shattered Pixel Dungeon's message files
// (core/src/main/assets/messages, GPL-3.0): the talents' and subclasses' names and descriptions, the lines of the buffs they
// bring and of the windows that show them, keyed as there. Do not edit by hand.

`;
writeFileSync(out, `${header}export const TAL_EN: Record<string, string> = {
${body(en)}
};
`);
writeFileSync(out.replace(/\.ts$/, '.ru.ts'), `${header}export const TAL_RU: Record<string, string> = {
${body(ru)}
};
`);
console.log(`${Object.keys(en).length} texts written to ${out}`);
